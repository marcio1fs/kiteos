import { NextRequest, NextResponse } from 'next/server';
import { z } from 'zod';
import { logger } from '@/lib/logger';
import { requireAuth } from '@/lib/auth';
import { reverseFinancialEntry } from '@/lib/reversals';
import { commercialErrorResponse, idSchema, paymentMethodSchema } from '@/lib/commercial';

const bodySchema = z.object({
  reason: z.string().trim().min(3, 'Informe o motivo do estorno').max(500),
  paymentMethod: paymentMethodSchema.optional(),
});

// POST /api/financial/[id]/estorno - reverse a PAID launch.
//
// This is the flow `DELETE /api/financial/[id]` has been pointing at since it
// started refusing to delete paid entries (BIZ-07): the original stays in the
// books as ESTORNADO and a compensating launch of the opposite type is written,
// so revenue is not erased and the ledger still adds up.
//
// Launches generated by a sale are rejected here — those are reversed through
// POST /api/sales/[id]/estorno, which also returns the stock.
export async function POST(
  request: NextRequest,
  { params }: { params: Promise<{ id: string }> },
) {
  try {
    const auth = await requireAuth(request, undefined, 'ADMIN');
    if (!auth.payload) {
      return NextResponse.json({ success: false, error: auth.error.message }, { status: auth.error.status });
    }

    const { id } = await params;
    const parsedId = idSchema.safeParse(id);
    if (!parsedId.success) {
      return NextResponse.json({ success: false, error: 'Identificador de lançamento inválido' }, { status: 400 });
    }

    const parsed = bodySchema.safeParse(await request.json().catch(() => null));
    if (!parsed.success) {
      return NextResponse.json(
        { success: false, error: 'Dados de estorno inválidos', details: parsed.error.flatten() },
        { status: 400 },
      );
    }

    const result = await reverseFinancialEntry(
      parsedId.data,
      auth.payload.officeId,
      { userId: auth.payload.userId, role: auth.payload.role },
      parsed.data,
    );

    return NextResponse.json({
      success: true,
      alreadyReversed: result.alreadyReversed,
      data: result,
    });
  } catch (error) {
    const known = commercialErrorResponse(error);
    if (known) return NextResponse.json(known.body, { status: known.status });
    logger.error('Error reversing financial entry:', { error: error instanceof Error ? error.message : String(error) });
    return NextResponse.json({ success: false, error: 'Erro ao estornar lançamento' }, { status: 500 });
  }
}
