/**
 * Parser de respostas SEFAZ
 * Extrai dados dos envelopes SOAP de retorno
 */

export interface SefazConsultaResult {
  cStat: string         // Código de status
  xMotivo: string       // Descrição do status
  protocolo: string | null  // Número do protocolo
  dhRecbto: string | null   // Data/hora recebimento
  chNFe: string         // Chave de acesso
  cUF: string | null    // Código da UF
  nfeStatus: 'AUTORIZADA' | 'CANCELADA' | 'DENEGADA' | 'INUTILIZADA' | 'NAO_ENCONTRADA' | 'ERRO'
  xmlContent: string | null  // XML da NF-e (se disponível na resposta)
  fornecedorCnpj: string | null  // CNPJ do emitente
}

export interface SefazDownloadResult {
  cStat: string
  xMotivo: string
  chNFe: string
  xmlContent: string | null  // XML autorizado completo
}

/**
 * Extrai valor de tag XML usando regex (mesmo padrão do xml-parser)
 */
function extractValue(xml: string, tag: string): string | null {
  const cleanTag = tag.replace(/[\w]+:/g, '')
  const patterns = [
    new RegExp(`<[\\w]*:?${escapeRegex(cleanTag)}[^>]*>([^<]+)</[\\w]*:?${escapeRegex(cleanTag)}>`, 'i'),
    new RegExp(`<${escapeRegex(cleanTag)}[^>]*>([^<]+)</${escapeRegex(cleanTag)}>`, 'i'),
  ]
  for (const pattern of patterns) {
    const match = xml.match(pattern)
    if (match && match[1]) return match[1].trim()
  }
  return null
}

function escapeRegex(str: string): string {
  return str.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
}

/**
 * Extrai bloco XML
 */
function extractBlock(xml: string, tag: string): string | null {
  const cleanTag = tag.replace(/[\w]+:/g, '')
  const pattern = new RegExp(
    `<[\\w]*:?${escapeRegex(cleanTag)}[^>]*>([\\s\\S]*?)</[\\w]*:?${escapeRegex(cleanTag)}>`,
    'i'
  )
  const match = xml.match(pattern)
  return match ? match[1] : null
}

/**
 * Mapeia cStat para status interno
 */
function mapCStatToStatus(cStat: string): SefazConsultaResult['nfeStatus'] {
  const authorized = ['100', '150'] // Autorizado o uso da NF-e / Autorizado o uso da NF-e
  const cancelled = ['101', '151', '218'] // Cancelamento / Cancelamento por substituição
  const denied = ['110', '205', '301', '302'] // Uso Denegado
  const unused = ['102', '217', '562'] // Inutilização

  if (authorized.includes(cStat)) return 'AUTORIZADA'
  if (cancelled.includes(cStat)) return 'CANCELADA'
  if (denied.includes(cStat)) return 'DENEGADA'
  if (unused.includes(cStat)) return 'INUTILIZADA'
  if (['516', '517', '518', '563', '564', '565', '567', '568', '578', '579', '580'].includes(cStat)) return 'NAO_ENCONTRADA'

  return 'ERRO'
}

/**
 * Parse da resposta de Consulta Protocolo
 * Extrai dados do envelope SOAP retornado pela SEFAZ
 */
export function parseConsultaProtocoloResponse(soapResponse: string): SefazConsultaResult {
  // Extrair corpo do SOAP
  const body = extractBlock(soapResponse, 'soap:Body') || extractBlock(soapResponse, 'Body') || soapResponse

  // Extrair retConsSitNFe
  const retConsSitNFe = extractBlock(body, 'retConsSitNFe') || body

  const cStat = extractValue(retConsSitNFe, 'cStat') || ''
  const xMotivo = extractValue(retConsSitNFe, 'xMotivo') || 'Resposta não identificada'
  const chNFe = extractValue(retConsSitNFe, 'chNFe') || ''
  const cUF = extractValue(retConsSitNFe, 'cUF')

  // Extrair protocolo de autorização
  let protocolo: string | null = null
  let dhRecbto: string | null = null
  let fornecedorCnpj: string | null = null

  // Buscar protocolo dentro de protNFe
  const protNFeBlock = extractBlock(retConsSitNFe, 'protNFe')
  if (protNFeBlock) {
    protocolo = extractValue(protNFeBlock, 'nProt')
    dhRecbto = extractValue(protNFeBlock, 'dhRecbto')

    // Tentar extrair CNPJ do emitente do XML do protocolo
    const infProtBlock = extractBlock(protNFeBlock, 'infProt')
    if (infProtBlock) {
      // Se houver XML dentro do protocolo, extrair emit/CNPJ
      const emitCnpj = extractValue(infProtBlock, 'CNPJ')
      if (emitCnpj) fornecedorCnpj = emitCnpj
    }
  }

  return {
    cStat,
    xMotivo,
    protocolo,
    dhRecbto,
    chNFe,
    cUF,
    nfeStatus: mapCStatToStatus(cStat),
    xmlContent: null, // Consulta protocolo não retorna XML completo
    fornecedorCnpj,
  }
}

/**
 * Parse da resposta de Download NF-e
 * Extrai XML autorizado da resposta
 */
export function parseDownloadNfeResponse(soapResponse: string): SefazDownloadResult {
  const body = extractBlock(soapResponse, 'soap:Body') || extractBlock(soapResponse, 'Body') || soapResponse

  const retDownloadNFe = extractBlock(body, 'retDownloadNFe') || body

  const cStat = extractValue(retDownloadNFe, 'cStat') || ''
  const xMotivo = extractValue(retDownloadNFe, 'xMotivo') || 'Resposta não identificada'
  const chNFe = extractValue(retDownloadNFe, 'chNFe') || ''

  // Extrair XML da NF-e
  let xmlContent: string | null = null
  const procNFeBlock = extractBlock(retDownloadNFe, 'procNFe')
  if (procNFeBlock) {
    // O procNFe contém o NFe + protNFe completo
    // Precisamos reconstruir o XML com a tag raiz
    xmlContent = `<?xml version="1.0" encoding="UTF-8"?><nfeProc xmlns="http://www.portalfiscal.inf.br/nfe">${procNFeBlock}</nfeProc>`
  }

  // Se não encontrou procNFe, tentar extrair NFe diretamente
  if (!xmlContent) {
    const nfeBlock = extractBlock(retDownloadNFe, 'NFe')
    if (nfeBlock) {
      xmlContent = `<?xml version="1.0" encoding="UTF-8"?><NFe xmlns="http://www.portalfiscal.inf.br/nfe">${nfeBlock}</NFe>`
    }
  }

  return {
    cStat,
    xMotivo,
    chNFe,
    xmlContent,
  }
}

/**
 * Parse da resposta de Status Serviço
 */
export function parseStatusServicoResponse(soapResponse: string): {
  cStat: string
  xMotivo: string
  dhRecbto: string | null
  tMed: string | null
  dhRetorno: string | null
  xObs: string | null
} {
  const body = extractBlock(soapResponse, 'soap:Body') || extractBlock(soapResponse, 'Body') || soapResponse
  const retConsStatServ = extractBlock(body, 'retConsStatServ') || body

  return {
    cStat: extractValue(retConsStatServ, 'cStat') || '',
    xMotivo: extractValue(retConsStatServ, 'xMotivo') || '',
    dhRecbto: extractValue(retConsStatServ, 'dhRecbto'),
    tMed: extractValue(retConsStatServ, 'tMed'),
    dhRetorno: extractValue(retConsStatServ, 'dhRetorno'),
    xObs: extractValue(retConsStatServ, 'xObs'),
  }
}

